import pandas as pd
import streamlit as st

st.set_page_config(page_title="Expense Dashboard", layout="wide")
st.title("Expense Dashboard")
st.caption("Sample data generated by sample_data/generate.py")

@st.cache_data
def load_data() -> pd.DataFrame:
    return pd.read_csv("sample_data/expenses_sample.csv", parse_dates=["day"])


df = load_data()
st.sidebar.header("Filters")

categories = st.sidebar.multiselect(
    "Categories",
    options=sorted(df["category"].unique()),
    default=sorted(df["category"].unique()),
)

start, end = st.sidebar.date_input(
    "Date range",
    value=(df["day"].min().date(), df["day"].max().date()),
)

mask = df["category"].isin(categories) & (df["day"].dt.date >= start) & (df["day"].dt.date <= end)
filtered = df[mask]
if filtered.empty:
    st.warning("No data for these filters.")
    st.stop()

#st.write(f"{len(df)} expenses loaded")
#st.dataframe(df)
with st.expander("Show raw data"):
    st.dataframe(filtered)
col1, col2, col3 = st.columns(3)
col1.metric("Total spent", f"{filtered['amount'].sum():.2f} €")
col2.metric("Average expense", f"{filtered['amount'].mean():.2f} €")
col3.metric("Number of expenses", f"{len(filtered)}")

st.subheader("Spending per category")
by_category = filtered.groupby("category")["amount"].sum().sort_values(ascending=False)
st.bar_chart(by_category)

st.subheader("Spending per month")
by_month = filtered.groupby(filtered["day"].dt.to_period("M").astype(str))["amount"].sum()
st.line_chart(by_month)